function boardFromBatches(batches) {
  const map = {
    QUEUED: ['CREATED', 'AWAITING_ISSUE', 'ISSUED', 'WAITING'],
    IN_PROGRESS: ['IN_TRANSIT', 'RECEIVED', 'IN_PROCESS'],
    QC: ['QC'],
    REWORK: ['REWORK'],
    HOLD: ['HOLD'],
    COMPLETED: ['COMPLETED', 'RETURNED_TO_VAULT'],
  }
  const board = Object.fromEntries(Object.keys(map).map((k) => [k, []]))
  for (const b of batches) {
    const col = Object.entries(map).find(([, statuses]) => statuses.includes(b.status))?.[0]
    if (col) board[col].push(b)
  }
  return board
}

