export function getDemoBatchDetail(batchId) {
  const batch = DEMO_BATCHES.find((b) => b._id === batchId)
  if (!batch) return null
  const expectedWeight = Number(batch.initialWeight || 0) - Number(batch.lossWeight || 0)
  const actualWeight = Number(batch.currentWeight || 0)
  const difference = actualWeight - expectedWeight
  const variancePct = expectedWeight > 0 ? (Math.abs(difference) / expectedWeight) * 100 : 0
  return {
    success: true,
    batch,
    movements: DEMO_MOVEMENTS.filter((m) => m.batchNumber === batch.batchNumber),
    passes: DEMO_PASSES.filter((p) => p.batchNumber === batch.batchNumber),
    processes: DEMO_PROCESSES.filter((p) => p.batchNumber === batch.batchNumber),
    qc: DEMO_QC.filter((q) => q.batchNumber === batch.batchNumber),
    adjustments: [],
    audits: DEMO_AUDIT.filter((a) => String(a.detail || '').includes(batch.batchNumber)),
    timeline: [
      { at: batch.createdAt, type: 'created', label: `Batch ${batch.batchNumber} created` },
      ...(batch.startedAt ? [{ at: batch.startedAt, type: 'started', label: 'Production started' }] : []),
      ...(batch.completedAt ? [{ at: batch.completedAt, type: 'completed', label: 'Batch completed' }] : []),
    ],
    weightReconciliation: {
      initialWeight: batch.initialWeight,
      issuedWeight: batch.issuedWeight,
      receivedWeight: batch.receivedWeight,
      processInput: batch.processInputWeight,
      processOutput: batch.processOutputWeight,
      scrap: batch.scrapWeight,
      loss: batch.lossWeight,
      recovered: batch.recoveredWeight,
      currentWeight: batch.currentWeight,
      expectedWeight,
      actualWeight,
      difference,
      variancePct,
    },
  }
}

export function getDemoWorkOrdersSummary() {
  const byWorkOrder = DEMO_WORK_ORDERS.map((wo) => {
    const linked = DEMO_BATCHES.filter((b) => b.workOrderId === wo._id)
    return {
      workOrderId: wo._id,
      workOrderNumber: wo.woNumber,
      batchCount: linked.length,
      activeCount: linked.filter((b) => !['COMPLETED', 'RETURNED_TO_VAULT', 'CANCELLED'].includes(b.status)).length,
      metalWeight: linked.reduce((s, b) => s + Number(b.currentWeight || 0), 0),
    }
  })
  return { success: true, byWorkOrder }
}
